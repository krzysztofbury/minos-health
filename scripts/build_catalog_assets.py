"""Offline concatenation of a pinned upstream search engine and the catalog UI."""

import argparse
import hashlib
from pathlib import Path
from typing import final

ROOT = Path(__file__).resolve().parents[1]
VENDOR_SHA256 = "03c27931eb603af1d3358579e9885eafdb6a2f5fa9929557b3e77d7e99d06d03"
LICENSE_SHA256 = "70d37354d6395629fb99edb28cb37a5d356ffa24a48cd02a5def5b83a300a899"


@final
class _Arguments(argparse.Namespace):
    check: bool = False


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--check", action="store_true")
    arguments = _Arguments()
    _ = parser.parse_args(namespace=arguments)
    vendor = ROOT / "apps/web/vendor"
    library = (vendor / "minisearch-7.2.0.js").read_bytes()
    license_text = (vendor / "minisearch-LICENSE.txt").read_bytes()
    if (
        hashlib.sha256(library).hexdigest() != VENDOR_SHA256
        or hashlib.sha256(license_text).hexdigest() != LICENSE_SHA256
    ):
        raise SystemExit("Pinned MiniSearch code/license identity mismatch.")
    ui = (ROOT / "apps/web/sources.js").read_bytes()
    result = (
        b"/* Generated by scripts/build_catalog_assets.py. Edit apps/web/sources.js. */\n"
        + b"/* MiniSearch 7.2.0 license:\n"
        + license_text
        + b"*/\n"
        + library
        + b"\n"
        + ui
    )
    output = ROOT / "infra/ansible/files/sources.js"
    if arguments.check:
        if not output.is_file() or output.read_bytes() != result:
            raise SystemExit("Catalog JavaScript is stale; rebuild it before shipping.")
    else:
        _ = output.write_bytes(result)


if __name__ == "__main__":
    main()
